// Refresh the checked-in shadow-root stylesheet copies. Native extension needs no build.
import fs from 'node:fs/promises';
const base=new URL('../extension/ui/',import.meta.url);
const read=async file=>(await fs.readFile(new URL(file,base),'utf8')).replace(/\r\n?/g,'\n');
const shared=await read('tokens.css')+await read('components.css'),popup=await read('popup.css');
const header='// Generated by scripts/sync_ui_styles.mjs; checked by ui-v1.test.mjs.\n';
await fs.writeFile(new URL('theme.js',base),header+'export const SHARED_CSS = '+JSON.stringify(shared)+';\n');
await fs.writeFile(new URL('popup-theme.js',base),header+'export const POPUP_CSS = '+JSON.stringify(popup)+';\n');
