// Keep the userscript fallback catalogue reviewable and available without an extension build.
import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const base = new URL('../extension/', import.meta.url);
const en = JSON.parse(await fs.readFile(new URL('_locales/en/messages.json', base), 'utf8'));
const zh = JSON.parse(await fs.readFile(new URL('_locales/zh_CN/messages.json', base), 'utf8'));
if (JSON.stringify(Object.keys(en).sort()) !== JSON.stringify(Object.keys(zh).sort())) throw Error('Locale keys differ');
const expand = record => record.message.replace(/\$(\w+)\$/g, (_,name) => record.placeholders?.[name.toLowerCase()]?.content ?? '');
const pairs = Object.fromEntries(Object.keys(en).map(key => [key, [expand(zh[key]), expand(en[key])]]));
const output = '// Generated by scripts/sync_i18n.mjs from the two Chrome catalogues.\nexport const messages = ' + JSON.stringify(pairs) + ';\n';
const target = new URL('shared/i18n-messages.js', base);
// Chrome selects zh_TW for Traditional Chinese browser UI. Its metadata must use
// the same Simplified Chinese copy as our runtime language policy.
const alias = new URL('_locales/zh_TW/messages.json', base);
const aliasText = JSON.stringify(zh,null,2)+'\n';
if (process.argv.includes('--check')) {
  if (await fs.readFile(target, 'utf8') !== output) throw Error('Run node scripts/sync_i18n.mjs');
  if (await fs.readFile(alias, 'utf8') !== aliasText) throw Error('Chinese locale alias differs');
} else {
  await fs.writeFile(target, output);
  await fs.mkdir(new URL('_locales/zh_TW/',base),{recursive:true});
  await fs.writeFile(alias,aliasText);
}
console.log(`PASS i18n catalogue: ${Object.keys(en).length} keys; fallback dictionary matches`);
